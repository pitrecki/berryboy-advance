#!/usr/bin/env bash
# Linux launcher for the vendor BlackBerry tools, using an existing Wine setup.
set -euo pipefail
project_root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
bb_sdk=${BB_JDE_HOME:-}
bb_jdk6=${BB_JDK6_HOME:-}
bb_simulator=${BB_SIMULATOR_HOME:-}
bb_model=9900
bb_launch=true
while (($#)); do
  [[ $# -ge 2 ]] || { echo "Missing value for $1" >&2; exit 2; }
  case "$1" in
    --sdk) bb_sdk=$2;;
    --jdk6) bb_jdk6=$2;;
    --simulator) bb_simulator=$2;;
    --model) bb_model=$2;;
    --launch) bb_launch=$2;;
    *) echo "Unknown option: $1" >&2; exit 2;;
  esac
  shift 2
done
[[ $bb_model =~ ^[A-Za-z0-9_-]+$ ]] || { echo 'Invalid simulator model/session' >&2; exit 2; }
[[ $bb_launch == true || $bb_launch == false ]] || { echo '--launch must be true or false' >&2; exit 2; }
for tool in wine winepath; do
  command -v "$tool" >/dev/null || { echo "Missing $tool. See docs/BLACKBERRY.md." >&2; exit 2; }
done
bb_api="$bb_sdk/lib/net_rim_api.jar"
for file in "$bb_api" "$bb_sdk/bin/rapc.exe" "$bb_jdk6/bin/javac.exe" "$bb_jdk6/bin/jar.exe"; do
  [[ -f $file ]] || { echo "Missing: $file. Configure BB_JDE_HOME and BB_JDK6_HOME (Windows tools in Wine)." >&2; exit 2; }
done
if [[ $bb_launch == true ]]; then
  for file in "$bb_simulator/$bb_model.bat" "$bb_simulator/fledgecontroller.exe"; do
    [[ -f $file ]] || { echo "Missing simulator file: $file" >&2; exit 2; }
  done
fi
build_root="$project_root/target/blackberry"
generated="$build_root/generated"
[[ -f "$generated/berryboy/Cpu.java" ]] || { echo 'Run Maven legacy-export first' >&2; exit 2; }
# These directories are exclusively generated by this project.
rm -rf -- "$build_root/classes" "$build_root/output"
mkdir -p -- "$build_root/classes" "$build_root/output"
windows_path() { winepath -w "$1" | tr -d '\r'; }
# The source list is a javac argument file, so use forward slashes inside quoted paths.
: > "$build_root/sources.args"
while IFS= read -r -d '' source; do
  win=$(windows_path "$source")
  printf '"%s"\n' "${win//\\//}" >> "$build_root/sources.args"
done < <(find "$generated" -name '*.java' -type f -print0)
win=$(windows_path "$project_root/platform/midp/berryboy/BlackBerryMidlet.java")
printf '"%s"\n' "${win//\\//}" >> "$build_root/sources.args"
classes_win=$(windows_path "$build_root/classes")
output_win=$(windows_path "$build_root/output")
api_win=$(windows_path "$bb_api")
jdk_win=$(windows_path "$bb_jdk6")
rapc_win=$(windows_path "$bb_sdk/bin/rapc.exe")
# Compile against the SDK API, not a desktop rt.jar. This is the actual CLDC API gate.
wine "$bb_jdk6/bin/javac.exe" -source 1.4 -target 1.4 -encoding UTF-8 \
  -bootclasspath "$api_win" -classpath "$classes_win" -d "$classes_win" \
  "@$(windows_path "$build_root/sources.args")"
midlet_jar="$build_root/output/BerryBoyAdvance.jar"
wine "$bb_jdk6/bin/jar.exe" cf "$(windows_path "$midlet_jar")" -C "$classes_win" .
jar_size=$(wc -c < "$midlet_jar" | tr -d ' ')
cat > "$build_root/output/BerryBoyAdvance.jad" <<JAD
MIDlet-Name: BerryBoy Advance
MIDlet-Version: 0.2.0
MIDlet-Vendor: BerryBoy
MIDlet-1: BerryBoy Advance,,berryboy.BlackBerryMidlet
MIDlet-Jar-URL: BerryBoyAdvance.jar
MIDlet-Jar-Size: $jar_size
MicroEdition-Profile: MIDP-2.0
MicroEdition-Configuration: CLDC-1.1
JAD
# Windows command processor expands %, ! and quotes; reject them in tool paths.
for value in "$output_win" "$api_win" "$jdk_win" "$rapc_win"; do
  case "$value" in *'%'*|*'!'*|*'"'*|*$'\n'*|*$'\r'*) echo 'Unsupported character in Wine tool path' >&2; exit 2;; esac
done
{
  printf '@echo off\r\n'
  printf 'set "PATH=%s\\bin;%%PATH%%"\r\n' "$jdk_win"
  printf 'cd /d "%s"\r\n' "$output_win"
  printf '"%s" "import=%s" codename=BerryBoyAdvance -midlet jad=BerryBoyAdvance.jad BerryBoyAdvance.jar\r\n' "$rapc_win" "$api_win"
  printf 'exit /b %%errorlevel%%\r\n'
} > "$build_root/rapc-build.cmd"
wine cmd /d /c "$(windows_path "$build_root/rapc-build.cmd")"
cod="$build_root/output/BerryBoyAdvance.cod"
[[ -s $cod ]] || { echo 'RAPC produced no COD' >&2; exit 1; }
printf 'Built: %s\n' "$cod"
if [[ $bb_launch == true ]]; then
  (
    cd -- "$bb_simulator"
    wine cmd /d /c "$bb_model.bat"
  ) > "$build_root/simulator.log" 2>&1 &
  cod_win=$(windows_path "$cod")
  cod_escaped=${cod_win//\\/\\\\}
  # Uses the vendor controller protocol; startup wait is bounded to 60 seconds.
  printf 'LoadCod("%s")\nquit\n' "$cod_escaped" | \
    wine "$bb_simulator/fledgecontroller.exe" "/session=$bb_model" /timeout=60 \
    | tee "$build_root/controller.log"
  echo 'Load command sent. Open BerryBoy Advance on the simulated device to run checks.'
  echo 'Only the on-device PASS/FAILED result verifies execution in the BB runtime.'
fi
